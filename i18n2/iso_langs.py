def iso_lang_list():
    """下拉数据：[code, native, en, zh]。POPULAR 在前，其余按代码字母序。

    zh-Hant（繁体中文）不是 ISO 639-1 码，但 add_language 的正则允许
    xx-XX 形态、且老版本预设里一直有，放在 zh 后面保留。
    """
    out = [[c, *ISO_LANGS[c]] for c in POPULAR if c in ISO_LANGS]
    out += [[c, *v] for c, v in sorted(ISO_LANGS.items()) if c not in POPULAR]
    for i, row in enumerate(out):
        if row[0] == "zh":
            out.insert(i + 1, ["zh-Hant", "繁體中文", "Traditional Chinese", "繁体中文"])
            break
    return out
